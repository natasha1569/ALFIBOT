CREATE OR REPLACE VIEW alfi.vw_reporte_actividad_usuarios AS
SELECT
    u.usuario_id,
    u.nombre AS usuario,
    u.correo,
    ro.nombre AS rol,
    count(DISTINCT a.analisis_id) AS total_analisis,
    count(DISTINCT a.analisis_id) FILTER (WHERE a.nivel_riesgo = 'alto') AS riesgos_altos,
    count(DISTINCT a.analisis_id) FILTER (WHERE a.nivel_riesgo = 'medio') AS riesgos_medios,
    count(DISTINCT a.analisis_id) FILTER (WHERE a.nivel_riesgo = 'bajo') AS riesgos_bajos,
    count(DISTINCT s.senal_id) AS total_senales,
    count(DISTINCT rec.recomendacion_id) AS total_recomendaciones,
    max(a.fecha_creacion) AS ultimo_analisis
FROM alfi.usuarios u
INNER JOIN alfi.roles ro
    ON u.rol_id = ro.rol_id
LEFT JOIN alfi.analisis a
    ON u.usuario_id = a.usuario_id
LEFT JOIN alfi.senales_alerta s
    ON a.analisis_id = s.analisis_id
LEFT JOIN alfi.recomendaciones rec
    ON a.analisis_id = rec.analisis_id
GROUP BY
    u.usuario_id,
    u.nombre,
    u.correo,
    ro.nombre;

CREATE OR REPLACE VIEW alfi.vw_reporte_riesgos_mensual AS
SELECT
    date_trunc('month', a.fecha_creacion)::date AS mes,
    a.nivel_riesgo,
    count(DISTINCT a.analisis_id) AS total_analisis,
    count(DISTINCT s.senal_id) AS total_senales,
    count(DISTINCT r.recomendacion_id) AS total_recomendaciones,
    round(
        count(DISTINCT a.analisis_id) * 100.0
        / sum(count(DISTINCT a.analisis_id)) OVER (
            PARTITION BY date_trunc('month', a.fecha_creacion)
        ),
        2
    ) AS porcentaje_mensual
FROM alfi.analisis a
LEFT JOIN alfi.senales_alerta s
    ON a.analisis_id = s.analisis_id
LEFT JOIN alfi.recomendaciones r
    ON a.analisis_id = r.analisis_id
GROUP BY
    date_trunc('month', a.fecha_creacion),
    a.nivel_riesgo;

CREATE OR REPLACE VIEW alfi.vw_reporte_fraude_riesgo AS
WITH analisis_detalle AS (
    SELECT
        a.analisis_id,
        date_trunc('month', a.fecha_creacion)::date AS mes,
        a.categoria_fraude,
        a.nivel_riesgo,
        a.tipo,
        count(DISTINCT s.senal_id) AS total_senales,
        count(DISTINCT r.recomendacion_id) AS total_recomendaciones
    FROM alfi.analisis a
    LEFT JOIN alfi.senales_alerta s
        ON s.analisis_id = a.analisis_id
    LEFT JOIN alfi.recomendaciones r
        ON r.analisis_id = a.analisis_id
    WHERE a.permitido = true
    GROUP BY
        a.analisis_id,
        date_trunc('month', a.fecha_creacion),
        a.categoria_fraude,
        a.nivel_riesgo,
        a.tipo
)
SELECT
    mes,
    categoria_fraude,
    nivel_riesgo,
    tipo,
    count(*) AS total_analisis,
    sum(total_senales)::bigint AS total_senales,
    sum(total_recomendaciones)::bigint AS total_recomendaciones,
    round(
        count(*) * 100.0
        / NULLIF(sum(count(*)) OVER (PARTITION BY mes), 0),
        2
    ) AS porcentaje_mensual
FROM analisis_detalle
GROUP BY
    mes,
    categoria_fraude,
    nivel_riesgo,
    tipo;

COMMENT ON VIEW alfi.vw_reporte_fraude_riesgo IS
    'BI agregado por mes, categoría soportada, riesgo y tipo de contenido; NULL indica análisis sin categoría de fraude soportada.';

CREATE OR REPLACE VIEW alfi.vw_reporte_contenido_perfil AS
WITH intereses_por_usuario AS (
    SELECT
        ui.usuario_id,
        string_agg(DISTINCT i.codigo, ', ' ORDER BY i.codigo) AS intereses_financieros
    FROM alfi.usuario_intereses_financieros ui
    INNER JOIN alfi.intereses_financieros i
        ON i.interes_id = ui.interes_id
       AND i.activo = true
    GROUP BY ui.usuario_id
)
SELECT
    date_trunc('month', a.fecha_creacion)::date AS mes,
    a.tipo,
    a.nivel_riesgo,
    a.categoria_fraude,
    COALESCE(u.provincia, 'No informado') AS provincia,
    COALESCE(u.rango_edad, 'No informado') AS rango_edad,
    COALESCE(ipu.intereses_financieros, 'Sin intereses registrados') AS intereses_financieros,
    count(DISTINCT a.analisis_id) AS total_analisis,
    count(DISTINCT a.usuario_id) AS usuarios_distintos,
    count(DISTINCT s.senal_id) AS total_senales
FROM alfi.analisis a
INNER JOIN alfi.usuarios u
    ON u.usuario_id = a.usuario_id
LEFT JOIN intereses_por_usuario ipu
    ON ipu.usuario_id = u.usuario_id
LEFT JOIN alfi.senales_alerta s
    ON s.analisis_id = a.analisis_id
WHERE a.permitido = true
GROUP BY
    date_trunc('month', a.fecha_creacion),
    a.tipo,
    a.nivel_riesgo,
    a.categoria_fraude,
    COALESCE(u.provincia, 'No informado'),
    COALESCE(u.rango_edad, 'No informado'),
    COALESCE(ipu.intereses_financieros, 'Sin intereses registrados');

COMMENT ON VIEW alfi.vw_reporte_contenido_perfil IS
    'BI agregado por contenido, riesgo, categoría soportada y atributos generales de perfil; no expone identidad individual.';

