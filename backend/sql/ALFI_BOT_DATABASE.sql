DO $$
DECLARE
    current_is_superuser boolean;
    current_can_create_role boolean;
BEGIN
    SELECT rolsuper, rolcreaterole
    INTO current_is_superuser, current_can_create_role
    FROM pg_roles
    WHERE rolname = current_user;

    IF COALESCE(current_is_superuser, false) = false
       AND COALESCE(current_can_create_role, false) = false THEN
        RAISE EXCEPTION
            'ALFI BOT: ejecute el instalador con un usuario PostgreSQL administrador que pueda crear roles (por ejemplo postgres).';
    END IF;
END
$$;

