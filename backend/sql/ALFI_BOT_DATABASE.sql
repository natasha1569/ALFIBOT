DO $$
DECLARE
    expected_tables text[] := ARRAY[
        'roles',
        'usuarios',
        'analisis',
        'senales_alerta',
        'recomendaciones',
        'auditoria',
        'intereses_financieros',
        'usuario_intereses_financieros'
    ];
    expected_views text[] := ARRAY[
        'vw_reporte_actividad_usuarios',
        'vw_reporte_riesgos_mensual',
        'vw_reporte_fraude_riesgo',
        'vw_reporte_contenido_perfil'
    ];
    object_name text;
BEGIN
    FOREACH object_name IN ARRAY expected_tables
    LOOP
        IF to_regclass(format('alfi.%I', object_name)) IS NULL THEN
            RAISE EXCEPTION 'ALFI BOT: falta la tabla alfi.%', object_name;
        END IF;
    END LOOP;

    FOREACH object_name IN ARRAY expected_views
    LOOP
        IF to_regclass(format('alfi.%I', object_name)) IS NULL THEN
            RAISE EXCEPTION 'ALFI BOT: falta la vista alfi.%', object_name;
        END IF;
    END LOOP;

    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgrelid = 'alfi.analisis'::regclass
          AND tgname = 'trg_auditoria_analisis'
          AND NOT tgisinternal
    ) THEN
        RAISE EXCEPTION 'ALFI BOT: falta trg_auditoria_analisis.';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgrelid = 'alfi.recomendaciones'::regclass
          AND tgname = 'trg_auditoria_recomendaciones'
          AND NOT tgisinternal
    ) THEN
        RAISE EXCEPTION 'ALFI BOT: falta trg_auditoria_recomendaciones.';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgrelid = 'alfi.usuarios'::regclass
          AND tgname = 'trg_auditoria_usuarios'
          AND NOT tgisinternal
    ) THEN
        RAISE EXCEPTION 'ALFI BOT: falta trg_auditoria_usuarios.';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgrelid = 'alfi.usuarios'::regclass
          AND tgname = 'trg_actualizar_fecha_usuario'
          AND NOT tgisinternal
    ) THEN
        RAISE EXCEPTION 'ALFI BOT: falta trg_actualizar_fecha_usuario.';
    END IF;

    IF EXISTS (SELECT 1 FROM alfi.roles WHERE nombre = 'analista') THEN
        RAISE EXCEPTION 'ALFI BOT: el rol funcional analista no debe existir.';
    END IF;

    IF (
        SELECT count(*)
        FROM alfi.roles
        WHERE nombre IN ('administrador', 'auditor', 'usuario')
    ) <> 3 THEN
        RAISE EXCEPTION 'ALFI BOT: catálogo de roles funcionales incompleto.';
    END IF;

    IF (
        SELECT count(*)
        FROM alfi.intereses_financieros
        WHERE activo = true
          AND codigo IN (
              'ahorro',
              'creditos_financiamiento',
              'inversiones',
              'seguros',
              'emprendimiento',
              'educacion_financiera'
          )
    ) <> 6 THEN
        RAISE EXCEPTION 'ALFI BOT: catálogo de intereses financieros incompleto.';
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM pg_roles
        WHERE rolname = 'rol_alfi_admin'
          AND rolcanlogin = false
          AND rolsuper = false
    ) OR NOT EXISTS (
        SELECT 1
        FROM pg_roles
        WHERE rolname = 'rol_alfi_auditor'
          AND rolcanlogin = false
          AND rolsuper = false
    ) OR NOT EXISTS (
        SELECT 1
        FROM pg_roles
        WHERE rolname = 'rol_alfi_usuario'
          AND rolcanlogin = false
          AND rolsuper = false
    ) THEN
        RAISE EXCEPTION 'ALFI BOT: los roles PostgreSQL RBAC no cumplen el estado esperado.';
    END IF;
END
$$;

COMMIT;

