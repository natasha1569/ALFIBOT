CREATE OR REPLACE FUNCTION alfi.fn_actualizar_fecha_usuario()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.fecha_actualizacion := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION alfi.fn_registrar_auditoria()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'alfi', 'public'
AS $$
DECLARE
    id_registro varchar(50);
BEGIN
    IF TG_OP = 'INSERT' THEN
        id_registro := to_jsonb(NEW) ->> TG_ARGV[0];

        INSERT INTO auditoria (
            tabla,
            operacion,
            registro_id,
            usuario_bd,
            fecha_operacion,
            datos_nuevos
        )
        VALUES (
            TG_TABLE_NAME,
            TG_OP,
            id_registro,
            SESSION_USER,
            CURRENT_TIMESTAMP,
            to_jsonb(NEW)
        );

        RETURN NEW;
    ELSIF TG_OP = 'UPDATE' THEN
        id_registro := to_jsonb(NEW) ->> TG_ARGV[0];

        INSERT INTO auditoria (
            tabla,
            operacion,
            registro_id,
            usuario_bd,
            fecha_operacion,
            datos_anteriores,
            datos_nuevos
        )
        VALUES (
            TG_TABLE_NAME,
            TG_OP,
            id_registro,
            SESSION_USER,
            CURRENT_TIMESTAMP,
            to_jsonb(OLD),
            to_jsonb(NEW)
        );

        RETURN NEW;
    ELSIF TG_OP = 'DELETE' THEN
        id_registro := to_jsonb(OLD) ->> TG_ARGV[0];

        INSERT INTO auditoria (
            tabla,
            operacion,
            registro_id,
            usuario_bd,
            fecha_operacion,
            datos_anteriores
        )
        VALUES (
            TG_TABLE_NAME,
            TG_OP,
            id_registro,
            SESSION_USER,
            CURRENT_TIMESTAMP,
            to_jsonb(OLD)
        );

        RETURN OLD;
    END IF;

    RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS trg_actualizar_fecha_usuario ON alfi.usuarios;
CREATE TRIGGER trg_actualizar_fecha_usuario
BEFORE UPDATE ON alfi.usuarios
FOR EACH ROW
EXECUTE FUNCTION alfi.fn_actualizar_fecha_usuario();

