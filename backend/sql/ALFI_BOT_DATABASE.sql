CREATE TABLE IF NOT EXISTS alfi.roles (
    rol_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(30) NOT NULL,
    descripcion varchar(150) NOT NULL,
    CONSTRAINT roles_nombre_key UNIQUE (nombre),
    CONSTRAINT chk_rol_nombre CHECK (char_length(btrim(nombre)) >= 3)
);

CREATE TABLE IF NOT EXISTS alfi.usuarios (
    usuario_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rol_id integer NOT NULL,
    nombre varchar(100) NOT NULL,
    correo varchar(120) NOT NULL,
    password_hash varchar(255) NOT NULL,
    activo boolean NOT NULL DEFAULT true,
    fecha_registro timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    celular varchar(10) NOT NULL,
    fecha_actualizacion timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    provincia varchar(40),
    rango_edad varchar(10),
    terminos_aceptados boolean,
    terminos_aceptados_en timestamp without time zone,
    terminos_version varchar(20),
    CONSTRAINT usuarios_correo_key UNIQUE (correo),
    CONSTRAINT fk_usuario_rol
        FOREIGN KEY (rol_id)
        REFERENCES alfi.roles(rol_id),
    CONSTRAINT chk_usuario_celular
        CHECK (celular ~ '^09[0-9]{8}$'),
    CONSTRAINT chk_usuario_correo
        CHECK (correo = lower(correo) AND correo LIKE '%@%'),
    CONSTRAINT chk_usuario_nombre
        CHECK (char_length(btrim(nombre)) >= 3),
    CONSTRAINT chk_usuario_password_hash
        CHECK (password_hash ~ '^\$2[aby]\$[0-9]{2}\$'),
    CONSTRAINT chk_usuario_provincia
        CHECK (
            provincia IS NULL
            OR provincia IN (
                'Azuay', 'Bolívar', 'Cañar', 'Carchi', 'Chimborazo',
                'Cotopaxi', 'El Oro', 'Esmeraldas', 'Galápagos', 'Guayas',
                'Imbabura', 'Loja', 'Los Ríos', 'Manabí', 'Morona Santiago',
                'Napo', 'Orellana', 'Pastaza', 'Pichincha', 'Santa Elena',
                'Santo Domingo de los Tsáchilas', 'Sucumbíos', 'Tungurahua',
                'Zamora Chinchipe'
            )
        ),
    CONSTRAINT chk_usuario_rango_edad
        CHECK (
            rango_edad IS NULL
            OR rango_edad IN ('18-24', '25-34', '35-44', '45-54', '55-64', '65+')
        ),
    CONSTRAINT chk_usuario_terminos_coherencia
        CHECK (
            (
                terminos_aceptados IS NULL
                AND terminos_aceptados_en IS NULL
                AND terminos_version IS NULL
            )
            OR
            (
                terminos_aceptados IS TRUE
                AND terminos_aceptados_en IS NOT NULL
                AND nullif(btrim(terminos_version), '') IS NOT NULL
            )
        )
);

CREATE TABLE IF NOT EXISTS alfi.analisis (
    analisis_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id integer NOT NULL,
    tipo varchar(20) NOT NULL,
    contenido text NOT NULL,
    vista_previa varchar(250),
    nivel_riesgo varchar(10) NOT NULL,
    resumen text NOT NULL,
    permitido boolean NOT NULL DEFAULT true,
    fecha_creacion timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    categoria_fraude varchar(40),
    CONSTRAINT fk_analisis_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES alfi.usuarios(usuario_id),
    CONSTRAINT chk_analisis_categoria_fraude
        CHECK (
            categoria_fraude IS NULL
            OR categoria_fraude IN (
                'credito_falso',
                'ponzi',
                'piramidal',
                'inversion_fraudulenta'
            )
        ),
    CONSTRAINT chk_analisis_contenido
        CHECK (char_length(btrim(contenido)) > 0),
    CONSTRAINT chk_analisis_resumen
        CHECK (char_length(btrim(resumen)) >= 5),
    CONSTRAINT chk_analisis_riesgo
        CHECK (nivel_riesgo IN ('bajo', 'medio', 'alto')),
    CONSTRAINT chk_analisis_tipo
        CHECK (tipo IN ('text', 'link', 'image')),
    CONSTRAINT chk_formato_link
        CHECK (tipo <> 'link' OR contenido ~* '^https?://'),
    CONSTRAINT chk_longitud_link
        CHECK (tipo <> 'link' OR char_length(contenido) <= 2000),
    CONSTRAINT chk_longitud_texto
        CHECK (tipo <> 'text' OR char_length(contenido) <= 5000)
);

CREATE TABLE IF NOT EXISTS alfi.senales_alerta (
    senal_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analisis_id integer NOT NULL,
    descripcion varchar(300) NOT NULL,
    orden integer NOT NULL DEFAULT 1,
    CONSTRAINT fk_senal_analisis
        FOREIGN KEY (analisis_id)
        REFERENCES alfi.analisis(analisis_id)
        ON DELETE CASCADE,
    CONSTRAINT uq_senal_orden UNIQUE (analisis_id, orden),
    CONSTRAINT chk_senal_descripcion
        CHECK (char_length(btrim(descripcion)) >= 5),
    CONSTRAINT chk_senal_orden
        CHECK (orden > 0)
);

CREATE TABLE IF NOT EXISTS alfi.recomendaciones (
    recomendacion_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analisis_id integer NOT NULL,
    descripcion varchar(400) NOT NULL,
    orden integer NOT NULL DEFAULT 1,
    CONSTRAINT fk_recomendacion_analisis
        FOREIGN KEY (analisis_id)
        REFERENCES alfi.analisis(analisis_id)
        ON DELETE CASCADE,
    CONSTRAINT uq_recomendacion_orden UNIQUE (analisis_id, orden),
    CONSTRAINT chk_recomendacion_descripcion
        CHECK (char_length(btrim(descripcion)) >= 5),
    CONSTRAINT chk_recomendacion_orden
        CHECK (orden > 0)
);

CREATE TABLE IF NOT EXISTS alfi.auditoria (
    auditoria_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tabla varchar(50) NOT NULL,
    operacion varchar(10) NOT NULL,
    registro_id varchar(50) NOT NULL,
    usuario_bd varchar(100) NOT NULL DEFAULT CURRENT_USER,
    fecha_operacion timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    datos_anteriores jsonb,
    datos_nuevos jsonb,
    CONSTRAINT chk_auditoria_operacion
        CHECK (operacion IN ('INSERT', 'UPDATE', 'DELETE'))
);

CREATE TABLE IF NOT EXISTS alfi.intereses_financieros (
    interes_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo varchar(40) NOT NULL,
    nombre varchar(80) NOT NULL,
    activo boolean NOT NULL DEFAULT true,
    fecha_creacion timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_intereses_financieros_codigo UNIQUE (codigo),
    CONSTRAINT uq_intereses_financieros_nombre UNIQUE (nombre),
    CONSTRAINT chk_intereses_financieros_codigo
        CHECK (codigo ~ '^[a-z0-9_]+$'),
    CONSTRAINT chk_intereses_financieros_nombre
        CHECK (char_length(btrim(nombre)) BETWEEN 3 AND 80)
);

CREATE TABLE IF NOT EXISTS alfi.usuario_intereses_financieros (
    usuario_id integer NOT NULL,
    interes_id integer NOT NULL,
    fecha_registro timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_usuario_intereses_financieros
        PRIMARY KEY (usuario_id, interes_id),
    CONSTRAINT fk_usuario_interes_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES alfi.usuarios(usuario_id)
        ON UPDATE CASCADE
        ON DELETE CASCADE,
    CONSTRAINT fk_usuario_interes_interes
        FOREIGN KEY (interes_id)
        REFERENCES alfi.intereses_financieros(interes_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
