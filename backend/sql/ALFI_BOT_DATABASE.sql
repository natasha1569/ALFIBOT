/*
===============================================================================
ALFI BOT — AFB-318 / T-22
Instalador canónico de PostgreSQL
===============================================================================

PROPÓSITO
- Permitir que cualquier integrante del equipo cree una base PostgreSQL vacía,
  abra este único archivo en pgAdmin Query Tool y ejecute todo el modelo ALFI.
- Consolidar el estado canónico observado en la base funcional del proyecto.
- Mantener compatibilidad con instalaciones anteriores mediante cambios
  aditivos/idempotentes conocidos.
- No almacenar contraseñas ni crear cuentas LOGIN.
- No eliminar datos de negocio existentes.

FLUJO ESPERADO
1. Crear una base PostgreSQL vacía (por ejemplo alfi_bot_db).
2. Abrir Query Tool conectado a esa base con un usuario administrador.
3. Ejecutar este archivo completo.
4. Configurar backend/.env apuntando a esa base.
5. Ejecutar npm run dev en backend y frontend.

IMPORTANTE
- Los roles PostgreSQL creados aquí son NOLOGIN y sirven exclusivamente para
  demostrar RBAC/mínimo privilegio. Las credenciales LOGIN se administran fuera
  del repositorio.
- El instalador no crea ni administra licencias comerciales.
===============================================================================
*/

